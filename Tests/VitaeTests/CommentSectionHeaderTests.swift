import Foundation
import Testing
@testable import Vitae

/// Комментарий лаборатории к результату («см. комм.») продолжается на следующих строках
/// без значений, но заголовок следующего раздела бланка — уже не комментарий.
@MainActor
@Suite("Заголовки разделов не попадают в комментарий")
struct CommentSectionHeaderTests {
    private func parse(_ lines: [String]) throws -> [ParsedLabItem] {
        let env = try TestEnvironment()
        return LabReportParser(catalog: env.store.catalogIndex()).parse(lines: lines).items
    }

    @Test func sectionHeaderEndsComment() throws {
        let items = try parse([
            "Витамин 25(ОН) D 25.0 нг/мл см.комм. < 10 нг/мл - выраженный дефицит;",
            "20-30 - недостаточность;",
            "30-100 - адекватный уровень",
            "Гормоны щитовидной железы",
            "Тиреотропный гормон (ТТГ) 2.1 мкМЕ/мл 0.4 - 4.0"
        ])
        #expect(items.map(\.testCode) == ["vitd", "tsh"])
        #expect(items.first?.comment == "< 10 нг/мл - выраженный дефицит; 20-30 - недостаточность; 30-100 - адекватный уровень")
        #expect(items.last?.rawValue == "2.1")
        #expect(items.last?.reference == ReferenceRange(lower: 0.4, upper: 4.0))
    }

    @Test func severalHeadersInARowAreSkipped() throws {
        let items = try parse([
            "Витамин 25(ОН) D 25.0 нг/мл см.комм. 30-100 нг/мл - адекватный уровень;",
            "> 100 нг/мл - избыток.",
            "Гормоны",
            "Гормоны щитовидной железы",
            "ТТГ 2.1 мкМЕ/мл 0.4 - 4.0"
        ])
        #expect(items.map(\.testCode) == ["vitd", "tsh"])
        #expect(items.first?.comment == "30-100 нг/мл - адекватный уровень; > 100 нг/мл - избыток.")
    }

    /// Строки текстового слоя синтетического бланка Инвитро (`OCRService.recognize(pdf:)`).
    @Test func invitroTextLayerKeepsZoneLabels() throws {
        let items = try parse([
            "ИНВИТРО",
            "Исследование  Результат  Единицы  Референсные значения  Комментарий",
            "Биохимические исследования крови",
            "Холестерин общий  5.1  ммоль/л  3.2 - 5.6",
            "Холестерин-ЛПНП (по  3.4  ммоль/л  см.комм.  Оптимальный уровень <2,6 ммоль/л.",
            "Фридвальду)  Желательный уровень <3,0 ммоль/л;",
            "для лиц с высоким риском <1,8 ммоль/л",
            "Триглицериды  0.9  ммоль/л  < 1.7",
            "Фосфатаза щелочная  61  Ед/л  40 - 129",
            "Витамины",
            "Витамин 25(ОН) D  25.0  нг/мл  см.комм.  < 10 нг/мл - выраженный дефицит;",
            "10-20 нг/мл - дефицит;",
            "20-30 нг/мл - недостаточность;",
            "30-100 нг/мл - адекватный уровень;",
            "> 100 нг/мл - избыток.",
            "Гормоны",
            "Тиреотропный гормон (ТТГ)  2.1  мкМЕ/мл  0.4 - 4.0",
            "Липопротеин (а)  18  мг/дл  см.комм.  Уровень <30 мг/дл указывает на низкий риск"
        ])
        func item(_ code: String) -> ParsedLabItem? { items.first { $0.testCode == code } }

        let vitD = try #require(item("vitd"))
        #expect(vitD.comment == "< 10 нг/мл - выраженный дефицит; 10-20 нг/мл - дефицит; 20-30 нг/мл - недостаточность; "
                + "30-100 нг/мл - адекватный уровень; > 100 нг/мл - избыток.")
        #expect(LabCommentInterpreter.label(for: ParsedValue.parse("120"), comment: vitD.comment) == "Избыток",
                "подпись зоны без заголовка раздела")
        #expect(vitD.reference.lower == 30)
        #expect(vitD.reference.upper == 100)

        let ldl = try #require(item("lipid.ldl"))
        #expect(ldl.name == "Холестерин-ЛПНП (по Фридвальду)")
        #expect(ldl.comment == "Оптимальный уровень <2,6 ммоль/л. Желательный уровень <3,0 ммоль/л; "
                + "для лиц с высоким риском <1,8 ммоль/л")
        #expect(item("tsh")?.rawValue == "2.1")
        #expect(item("alp")?.comment == "")
    }

    /// Продолжение комментария с заглавной буквы и без цифр остаётся в комментарии:
    /// за ним идёт текст комментария или оно заканчивается точкой.
    @Test func capitalizedContinuationStaysInComment() throws {
        let items = try parse([
            "Холестерин-ЛПНП (по 2.41 ммоль/л см.комм Рекомендации по интерпретации: при",
            "Фридвальду) отсутствии дополнительных факторов",
            "кардиориска желательный уровень <3,0 ммоль/л.",
            "Индивидуальные целевые значения ХС ЛПНП для",
            "пациентов высокого и очень высокого",
            "риска определяет врач.",
            "Холестерин не-ЛПВП 2.96 ммоль/л см.комм. Желательный уровень <3,8 ммоль/л.",
            "Индивидуальные целевые значения определяет врач.",
            "Фосфатаза щелочная 96 Ед/л 40 - 150"
        ])
        #expect(items.map(\.testCode) == ["lipid.ldl", "lipid.nonhdl", "alp"])
        #expect(items[0].name == "Холестерин-ЛПНП (по Фридвальду)")
        #expect(items[0].comment == "Рекомендации по интерпретации: при отсутствии дополнительных факторов "
                + "кардиориска желательный уровень <3,0 ммоль/л. Индивидуальные целевые значения ХС ЛПНП для "
                + "пациентов высокого и очень высокого риска определяет врач.")
        #expect(items[1].comment == "Желательный уровень <3,8 ммоль/л. Индивидуальные целевые значения определяет врач.")
    }

    /// Окончание названия на отдельной строке («Фридвальду)») похоже на заголовок, но им не является.
    @Test func nameContinuationBeforeNextResultIsKept() throws {
        let items = try parse([
            "Холестерин-ЛПНП (по 2.41 ммоль/л см.комм. Желательный уровень <3,0 ммоль/л.",
            "Фридвальду)",
            "Фосфатаза щелочная 96 Ед/л 40 - 150"
        ])
        #expect(items.map(\.testCode) == ["lipid.ldl", "alp"])
        #expect(items.first?.name == "Холестерин-ЛПНП (по Фридвальду)")
        #expect(items.first?.comment == "Желательный уровень <3,0 ммоль/л.")
    }
}
